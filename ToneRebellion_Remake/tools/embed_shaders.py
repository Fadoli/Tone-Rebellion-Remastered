"""Embeds the presentation shaders into src/platform/sdl/sdl_gl_shaders.h.

Reads shaders/ (libretro GLSL presets, kept with their own notices, and the
remake's own shaders) and writes C string tables, the preset pass lists and
the LUT PNG bytes, so the build needs no Python and no shader files at run
time. Run after changing anything under shaders/:

    python tools/embed_shaders.py
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHADERS = os.path.join(ROOT, "shaders")
OUT = os.path.join(ROOT, "src", "platform", "sdl", "sdl_gl_shaders.h")

# Remake filter -> preset (path under shaders/, or a built-in pass list).
# "stock" passes take the pass filter from the preset entry.
PRESETS = [
    ("nearest", None, [("remake/stock.glsl", False)]),
    ("bilinear", None, [("remake/stock.glsl", True)]),
    ("sharp_bilinear", "libretro/interpolation/sharp-bilinear.glslp", None),
    ("bicubic", "libretro/cubic/catmull-rom.glslp", None),
    ("lanczos3", None, [("remake/lanczos3.glsl", False)]),
    ("xbr", "libretro/xbr/xbr-lv2.glslp", None),
    ("hq2x", "libretro/hqx/hq2x.glslp", None),
    ("hq3x", "libretro/hqx/hq3x.glslp", None),
    ("hq4x", "libretro/hqx/hq4x.glslp", None),
    ("scalefx", "libretro/scalefx/scalefx.glslp", None),
]


def parse_preset(path):
    values = {}
    for line in open(os.path.join(SHADERS, path), encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip().strip('"')
    base = os.path.dirname(path)
    passes = []
    for i in range(int(values["shaders"])):
        shader = os.path.normpath(os.path.join(base, values["shader%d" % i])).replace("\\", "/")
        passes.append({
            "shader": shader,
            "linear": values.get("filter_linear%d" % i, "false") == "true",
            "scale_type": values.get("scale_type%d" % i, ""),
            "scale": float(values.get("scale%d" % i, "1.0")),
            "float_fb": values.get("float_framebuffer%d" % i, "false") == "true",
        })
    lut = None
    if "textures" in values:
        name = values["textures"].split(";")[0]
        lut = (name, os.path.normpath(os.path.join(base, values[name])).replace("\\", "/"),
               values.get(name + "_linear", "false") == "true")
    params = []
    if "parameters" in values:
        for name in values["parameters"].split(";"):
            params.append((name, float(values[name])))
    return passes, lut, params


def c_string(text):
    out = []
    for line in text.replace("\r\n", "\n").split("\n"):
        line = line.replace("\\", "\\\\").replace('"', '\\"')
        out.append('    "%s\\n"' % line)
    return "\n".join(out)


def main():
    shaders = []      # paths in table order
    luts = []
    presets = []
    for name, preset_path, builtin in PRESETS:
        if preset_path:
            passes, lut, params = parse_preset(preset_path)
        else:
            passes = [{"shader": s, "linear": lin, "scale_type": "", "scale": 1.0,
                       "float_fb": False} for s, lin in builtin]
            lut, params = None, []
        for p in passes:
            if p["shader"] not in shaders:
                shaders.append(p["shader"])
            p["index"] = shaders.index(p["shader"])
        lut_index = -1
        if lut:
            if lut[1] not in [l[1] for l in luts]:
                luts.append(lut)
            lut_index = [l[1] for l in luts].index(lut[1])
        presets.append((name, passes, lut_index, lut[2] if lut else False, params))

    w = []
    w.append("/* Generated by tools/embed_shaders.py from shaders/; do not edit.")
    w.append("   The libretro files keep their own notices (see the README). */")
    w.append("")
    for i, path in enumerate(shaders):
        text = open(os.path.join(SHADERS, path), encoding="utf-8").read()
        w.append("/* shaders/%s */" % path)
        w.append("static const char g_gl_shader_%d[] =" % i)
        w.append(c_string(text) + ";")
        w.append("")
    for i, lut in enumerate(luts):
        data = open(os.path.join(SHADERS, lut[1]), "rb").read()
        w.append("/* shaders/%s (PNG) */" % lut[1])
        w.append("static const unsigned char g_gl_lut_%d[%d] = {" % (i, len(data)))
        for j in range(0, len(data), 20):
            w.append("    " + ",".join(str(b) for b in data[j:j + 20]) + ",")
        w.append("};")
        w.append("")
    w.append("static const char *const g_gl_shader_sources[] = {")
    for i in range(len(shaders)):
        w.append("    g_gl_shader_%d," % i)
    w.append("};")
    w.append("static const struct { const unsigned char *png; unsigned size; const char *name; } g_gl_luts[] = {")
    for i, lut in enumerate(luts):
        w.append('    {g_gl_lut_%d, sizeof(g_gl_lut_%d), "%s"},' % (i, i, lut[0]))
    if not luts:
        w.append("    {0, 0, 0},")
    w.append("};")
    w.append("")
    w.append("enum { GL_PRESET_MAX_PASSES = 6, GL_PRESET_MAX_PARAMS = 2 };")
    w.append("typedef struct GlPassDesc {")
    w.append("    int shader;        /* g_gl_shader_sources index */")
    w.append("    int linear;        /* sample the pass input with GL_LINEAR */")
    w.append("    int source_scale;  /* 1: output = input x scale; 0: viewport (last pass only) */")
    w.append("    float scale;")
    w.append("    int float_fb;      /* float framebuffer */")
    w.append("} GlPassDesc;")
    w.append("typedef struct GlPresetDesc {")
    w.append("    const char *name;")
    w.append("    int pass_count;")
    w.append("    GlPassDesc passes[GL_PRESET_MAX_PASSES];")
    w.append("    int lut;           /* g_gl_luts index or -1 */")
    w.append("    int lut_linear;")
    w.append("    int param_count;")
    w.append("    struct { const char *name; float value; } params[GL_PRESET_MAX_PARAMS];")
    w.append("} GlPresetDesc;")
    w.append("")
    w.append("static const GlPresetDesc g_gl_presets[] = {")
    for name, passes, lut_index, lut_linear, params in presets:
        items = []
        for k, p in enumerate(passes):
            last = k == len(passes) - 1
            source = p["scale_type"] == "source" or (p["scale_type"] == "" and not last)
            items.append("{%d, %d, %d, %.1ff, %d}" % (p["index"], int(p["linear"]), int(source),
                                                     p["scale"], int(p["float_fb"])))
        param_text = ", ".join('{"%s", %.1ff}' % (n, v) for n, v in params) or '{0, 0.0f}'
        w.append('    {"%s", %d, {%s}, %d, %d, %d, {%s}},' % (
            name, len(passes), ", ".join(items), lut_index, int(lut_linear), len(params),
            param_text))
    w.append("};")
    w.append("enum { GL_PRESET_COUNT = sizeof(g_gl_presets) / sizeof(g_gl_presets[0]) };")
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(w) + "\n")
    print("wrote %s: %d shaders, %d LUTs, %d presets" % (OUT, len(shaders), len(luts), len(presets)))


if __name__ == "__main__":
    sys.exit(main())
